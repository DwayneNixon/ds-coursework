"""X4 evidence consolidation from D1, D2 and measured D3 trial files.

Use existing committed three-trial D1/D2 logs and the D3 CSV generated by
python -m Part_D_Tests.run_d3_benchmark --output results/audit_d3/comparison.csv
Run: python -m experiments.x4_comparison
"""
import argparse
import csv
import json
import re
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CONFIG = ROOT / "configs" / "x4_comparison.json"


def get_number(text, name):
    m = re.search(r"^" + re.escape(name) + r":\s*([0-9.]+)", text, re.M)
    if m is None:
        raise ValueError(f"Missing metric {name}")
    return float(m.group(1))


def read_log(relative_path):
    path = ROOT / relative_path
    raw = path.read_bytes()
    # Several original trial logs were saved through Windows PowerShell,
    # which produces UTF-16 with a BOM; others were saved as UTF-8.
    text = (
        raw.decode("utf-16")
        if raw.startswith((bytes.fromhex("fffe"), bytes.fromhex("feff")))
        else raw.decode("utf-8-sig")
    )
    if "Final parameter correctness: PASS" not in text:
        raise ValueError(f"Unverified old experiment log: {path}")
    return {
        "total_bytes": get_number(text, "Total bytes"),
        "push_p99_ms": get_number(text, "Push P99"),
        "pull_p99_ms": get_number(text, "Pull P99"),
    }


def median_logs(folder, template):
    records = [read_log(Path(folder) / template.format(i))
               for i in (1, 2, 3)]
    return {
        field: statistics.median(row[field] for row in records)
        for field in records[0]
    }


def make_row(name, before, after, latency_type, note=""):
    initial = before["total_bytes"]
    final = after["total_bytes"]
    return {
        "optimization": name,
        "baseline_bytes": round(initial, 4),
        "optimized_bytes": round(final, 4),
        "bytes_saved_percent": round(100 * (1 - final / initial), 4),
        "baseline_p99_ms": round(before[latency_type], 4),
        "optimized_p99_ms": round(after[latency_type], 4),
        "p99_definition": latency_type,
        "notes": note,
    }


def run(config, output_dir):
    if config.get("experiment") != "X4_communication_optimizations":
        raise ValueError("Incorrect X4 config")
    inputs = config["inputs"]
    d1 = inputs["d1_cache"]
    d2 = inputs["d2_compression"]
    cache_off = median_logs(d1, "off_trial_{}.txt")
    cache_on = median_logs(d1, "on_trial_{}.txt")
    baseline = median_logs(d2, "baseline_trial_{}.txt")
    compressed = median_logs(d2, "compression_trial_{}.txt")
    combined = median_logs(d2, "combined_trial_{}.txt")
    rows = [
        make_row("D1_sparse_key_cache", cache_off, cache_on, "push_p99_ms",
                 "Three historical D1 trials, median comparison"),
        make_row("D2_lossless_compression", baseline, compressed, "push_p99_ms",
                 "Three historical D2 trials, median comparison"),
        make_row("D1_D2_combined", baseline, combined, "push_p99_ms",
                 "Three historical D2 trials, median comparison"),
    ]

    d3_path = ROOT / inputs["d3_batching"]
    with d3_path.open(newline="", encoding="utf-8") as handle:
        d3 = list(csv.DictReader(handle))
    if len(d3) != 6 or {x["mode"] for x in d3} != {"batched", "unbatched"}:
        raise ValueError("Expected exactly three D3 trials in each mode")
    d3_summary = {}
    for mode in ("unbatched", "batched"):
        matching = [x for x in d3 if x["mode"] == mode]
        if len(matching) != 3:
            raise ValueError("D3 trial count mismatch")
        d3_summary[mode] = {
            "total_bytes": statistics.median(
                float(x["total_bytes"]) for x in matching),
            "p99_latency_ms": statistics.median(
                float(x["p99_latency_ms"]) for x in matching),
            "physical_rpcs": statistics.median(
                float(x["physical_rpcs"]) for x in matching),
        }
    # A batch is a logical group of Pulls, not a Push. Keep its latency
    # separate from D1/D2's Push p99 for an honest comparison.
    rows.append(make_row(
        "D3_sparse_pull_batching", d3_summary["unbatched"],
        d3_summary["batched"], "p99_latency_ms",
        "D3 group-of-eight Pull latency, three matched trials",
    ))

    output = Path(output_dir)
    if not output.is_absolute():
        output = ROOT / output
    output.mkdir(parents=True, exist_ok=True)
    with (output / "comparison.csv").open(
        "w", newline="", encoding="utf-8"
    ) as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axs = plt.subplots(1, 2, figsize=(12, 4.5))
    labels = [r["optimization"].replace("_", "\n") for r in rows]
    x = list(range(len(rows)))
    axs[0].bar([i - 0.17 for i in x],
               [r["baseline_bytes"] for r in rows], width=0.34, label="Baseline")
    axs[0].bar([i + 0.17 for i in x],
               [r["optimized_bytes"] for r in rows], width=0.34, label="Optimized")
    axs[0].set(title="X4 — Serialized payload bytes", xticks=x,
               xticklabels=labels, ylabel="Median total bytes")
    axs[0].legend()
    axs[1].bar(x, [r["bytes_saved_percent"] for r in rows])
    axs[1].set(title="X4 — Communication reduction",
               xticks=x, xticklabels=labels, ylabel="Bytes saved (%)")
    fig.tight_layout()
    fig.savefig(output / "comparison.png", dpi=160)
    plt.close(fig)

    details = {
        "experiment": "X4_communication_optimizations",
        "trials_per_case": 3,
        "rows": rows,
        "d3_rpc_reduction_percent": 100 * (
            1 - d3_summary["batched"]["physical_rpcs"]
            / d3_summary["unbatched"]["physical_rpcs"]
        ),
        "caution": (
            "D1/D2 rows measure Push p99, D3 measures group-of-Pulls p99. "
            "These are not directly comparable latency types. "
            "All byte figures count serialized application payloads, "
            "not TCP/gRPC overhead or backup replication traffic."
        ),
        "historical_inputs": inputs,
    }
    (output / "summary.json").write_text(
        json.dumps(details, indent=2), encoding="utf-8"
    )
    return details


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=str(DEFAULT_CONFIG))
    ap.add_argument("--output")
    args = ap.parse_args()
    cfg = json.loads(Path(args.config).read_text(encoding="utf-8"))
    result = run(cfg, args.output or cfg["output_dir"])
    print("X4 three-optimization comparison: PASS")
    for row in result["rows"]:
        print(row["optimization"], row["bytes_saved_percent"], "% bytes saved")


if __name__ == "__main__":
    main()
